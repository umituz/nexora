import SwiftUI

// MARK: - Research Report Viewer

struct ResearchViewerView: View {
    let output: AgentOutput
    @State private var expandedSection: String? = "Key Findings"
    @State private var selectedTab = 0

    private let tabs = ["Report", "Sources", "Data"]

    var body: some View {
        VStack(spacing: 0) {
            reportHeader
            tabBar
            ScrollView(showsIndicators: false) {
                Group {
                    switch selectedTab {
                    case 0: reportContent
                    case 1: sourcesContent
                    default: dataContent
                    }
                }
                .padding(.bottom, 30)
            }
            .background(Color.black)
        }
        .background(Color.black)
    }

    // MARK: - Report Header

    @ViewBuilder
    private var reportHeader: some View {
        VStack(alignment: .leading, spacing: 12) {
            HStack(spacing: 10) {
                Image(systemName: "doc.text.magnifyingglass")
                    .font(.system(size: 14))
                    .foregroundStyle(.orange)
                    .frame(width: 32, height: 32)
                    .background(Color.orange.opacity(0.15))
                    .clipShape(RoundedRectangle(cornerRadius: 9))
                VStack(alignment: .leading, spacing: 2) {
                    Text("Market Research Report")
                        .font(.subheadline).fontWeight(.bold).foregroundStyle(.white)
                    Text("Generated by Nexus Agent · 47 sources")
                        .font(.caption).foregroundStyle(.gray)
                }
                Spacer()
                Text("Q4 2025")
                    .font(.caption)
                    .fontWeight(.semibold)
                    .foregroundStyle(.orange)
                    .padding(.horizontal, 10)
                    .padding(.vertical, 5)
                    .background(Color.orange.opacity(0.15))
                    .clipShape(Capsule())
            }
            metaRow
        }
        .padding(16)
        .background(Color(white: 0.07))
    }

    @ViewBuilder
    private var metaRow: some View {
        HStack(spacing: 0) {
            ForEach([("8", "Competitors"), ("2,400", "Reviews"), ("47", "Sources"), ("12", "Pages")], id: \.0) { val, lbl in
                VStack(spacing: 2) {
                    Text(val).font(.subheadline).fontWeight(.bold).foregroundStyle(.white)
                    Text(lbl).font(.caption2).foregroundStyle(.gray)
                }
                .frame(maxWidth: .infinity)
            }
        }
        .padding(.vertical, 10)
        .background(Color.white.opacity(0.05))
        .clipShape(RoundedRectangle(cornerRadius: 12))
    }

    // MARK: - Tab Bar

    @ViewBuilder
    private var tabBar: some View {
        HStack(spacing: 0) {
            ForEach(tabs.indices, id: \.self) { i in
                Button {
                    withAnimation(.spring(duration: 0.25)) { selectedTab = i }
                } label: {
                    VStack(spacing: 7) {
                        Text(tabs[i])
                            .font(.subheadline)
                            .fontWeight(selectedTab == i ? .semibold : .regular)
                            .foregroundStyle(selectedTab == i ? .white : .gray)
                        Rectangle()
                            .fill(selectedTab == i ? Color.orange : Color.clear)
                            .frame(height: 2)
                    }
                }
                .frame(maxWidth: .infinity)
            }
        }
        .padding(.horizontal, 20)
        .background(Color.black)
    }

    // MARK: - Report Tab

    @ViewBuilder
    private var reportContent: some View {
        VStack(spacing: 16) {
            executiveSummary
            ForEach(ResearchData.sections) { section in
                collapsibleSection(section)
            }
        }
        .padding(.horizontal, 20)
        .padding(.top, 16)
    }

    @ViewBuilder
    private var executiveSummary: some View {
        VStack(alignment: .leading, spacing: 10) {
            Label("Executive Summary", systemImage: "star.fill")
                .font(.subheadline).fontWeight(.bold).foregroundStyle(.orange)
            Text(ResearchData.executiveSummary)
                .font(.subheadline)
                .foregroundStyle(.white.opacity(0.85))
                .lineSpacing(5)
            HStack(spacing: 8) {
                ForEach(ResearchData.keyTags, id: \.self) { tag in
                    Text(tag)
                        .font(.caption2).fontWeight(.medium)
                        .foregroundStyle(.orange.opacity(0.9))
                        .padding(.horizontal, 10).padding(.vertical, 4)
                        .background(Color.orange.opacity(0.12))
                        .clipShape(Capsule())
                }
            }
        }
        .padding(16)
        .background(Color.orange.opacity(0.07))
        .overlay(RoundedRectangle(cornerRadius: 16).stroke(Color.orange.opacity(0.2), lineWidth: 1))
        .clipShape(RoundedRectangle(cornerRadius: 16))
    }

    @ViewBuilder
    private func collapsibleSection(_ section: ResearchSection) -> some View {
        let isExpanded = expandedSection == section.title
        VStack(spacing: 0) {
            Button {
                withAnimation(.spring(duration: 0.3)) {
                    expandedSection = isExpanded ? nil : section.title
                }
            } label: {
                HStack(spacing: 12) {
                    Image(systemName: section.icon)
                        .font(.system(size: 14))
                        .foregroundStyle(section.color)
                        .frame(width: 32, height: 32)
                        .background(section.color.opacity(0.12))
                        .clipShape(RoundedRectangle(cornerRadius: 9))
                    Text(section.title)
                        .font(.subheadline).fontWeight(.semibold).foregroundStyle(.white)
                    Spacer()
                    Image(systemName: "chevron.down")
                        .font(.caption)
                        .foregroundStyle(.gray)
                        .rotationEffect(.degrees(isExpanded ? 180 : 0))
                }
                .padding(14)
            }
            if isExpanded {
                VStack(alignment: .leading, spacing: 10) {
                    ForEach(section.findings, id: \.self) { finding in
                        findingRow(finding)
                    }
                }
                .padding(.horizontal, 14)
                .padding(.bottom, 14)
            }
        }
        .background(Color.white.opacity(0.05))
        .clipShape(RoundedRectangle(cornerRadius: 16))
    }

    @ViewBuilder
    private func findingRow(_ text: String) -> some View {
        HStack(alignment: .top, spacing: 10) {
            Circle()
                .fill(Color.orange.opacity(0.6))
                .frame(width: 5, height: 5)
                .padding(.top, 6)
            Text(text)
                .font(.subheadline)
                .foregroundStyle(.white.opacity(0.8))
                .lineSpacing(4)
        }
    }

    // MARK: - Sources Tab

    @ViewBuilder
    private var sourcesContent: some View {
        VStack(spacing: 10) {
            ForEach(ResearchData.sources) { source in
                SourceRow(source: source)
            }
        }
        .padding(.horizontal, 20)
        .padding(.top, 16)
    }

    // MARK: - Data Tab

    @ViewBuilder
    private var dataContent: some View {
        VStack(spacing: 16) {
            sentimentChart
            competitorMatrix
        }
        .padding(.horizontal, 20)
        .padding(.top, 16)
    }

    @ViewBuilder
    private var sentimentChart: some View {
        VStack(alignment: .leading, spacing: 14) {
            Text("User Sentiment by Competitor")
                .font(.subheadline).fontWeight(.bold).foregroundStyle(.white)
            VStack(spacing: 10) {
                ForEach(ResearchData.sentimentData) { item in
                    SentimentBar(item: item)
                }
            }
        }
        .padding(16)
        .background(Color.white.opacity(0.05))
        .clipShape(RoundedRectangle(cornerRadius: 16))
    }

    @ViewBuilder
    private var competitorMatrix: some View {
        VStack(alignment: .leading, spacing: 14) {
            Text("Feature Matrix")
                .font(.subheadline).fontWeight(.bold).foregroundStyle(.white)
            ScrollView(.horizontal, showsIndicators: false) {
                competitorTable
            }
        }
        .padding(16)
        .background(Color.white.opacity(0.05))
        .clipShape(RoundedRectangle(cornerRadius: 16))
    }

    @ViewBuilder
    private var competitorTable: some View {
        let features = ["AI Agents", "Multi-step", "Integrations", "Mobile App", "API Access"]
        let competitors = ResearchData.competitors

        VStack(spacing: 0) {
            // Header
            HStack(spacing: 0) {
                Text("Feature").font(.caption).fontWeight(.semibold).foregroundStyle(.gray)
                    .frame(width: 110, alignment: .leading)
                ForEach(competitors, id: \.name) { c in
                    Text(c.name).font(.caption2).fontWeight(.semibold).foregroundStyle(c.isUs ? .orange : .gray)
                        .frame(width: 70)
                }
            }
            .padding(.bottom, 8)
            Divider().background(Color.white.opacity(0.1))
            // Rows
            ForEach(features, id: \.self) { feature in
                HStack(spacing: 0) {
                    Text(feature).font(.caption).foregroundStyle(.white.opacity(0.8))
                        .frame(width: 110, alignment: .leading)
                    ForEach(competitors, id: \.name) { c in
                        let has = c.features.contains(feature)
                        Image(systemName: has ? "checkmark.circle.fill" : "xmark.circle")
                            .font(.system(size: 14))
                            .foregroundStyle(has ? (c.isUs ? Color.orange : Color.green) : Color.white.opacity(0.2))
                            .frame(width: 70)
                    }
                }
                .padding(.vertical, 6)
                Divider().background(Color.white.opacity(0.05))
            }
        }
    }
}

// MARK: - Source Row

struct SourceRow: View {
    let source: ResearchSource

    var body: some View {
        HStack(spacing: 12) {
            Text(source.favicon)
                .font(.title3)
                .frame(width: 38, height: 38)
                .background(Color.white.opacity(0.07))
                .clipShape(RoundedRectangle(cornerRadius: 10))
            VStack(alignment: .leading, spacing: 3) {
                Text(source.title)
                    .font(.subheadline).fontWeight(.medium).foregroundStyle(.white).lineLimit(1)
                Text(source.domain)
                    .font(.caption).foregroundStyle(.gray)
            }
            Spacer()
            HStack(spacing: 4) {
                Image(systemName: "chart.bar.fill").font(.caption2).foregroundStyle(source.reliabilityColor)
                Text(source.reliability)
                    .font(.caption2).fontWeight(.semibold).foregroundStyle(source.reliabilityColor)
            }
        }
        .padding(12)
        .background(Color.white.opacity(0.05))
        .clipShape(RoundedRectangle(cornerRadius: 14))
    }
}

// MARK: - Sentiment Bar

struct SentimentBar: View {
    let item: SentimentItem

    var body: some View {
        VStack(spacing: 5) {
            HStack {
                Text(item.name).font(.caption).fontWeight(.medium).foregroundStyle(.white)
                Spacer()
                Text("\(Int(item.score * 100))%").font(.caption).fontWeight(.bold).foregroundStyle(item.color)
            }
            GeometryReader { geo in
                ZStack(alignment: .leading) {
                    RoundedRectangle(cornerRadius: 4).fill(Color.white.opacity(0.08)).frame(height: 6)
                    RoundedRectangle(cornerRadius: 4)
                        .fill(LinearGradient(colors: [item.color.opacity(0.8), item.color], startPoint: .leading, endPoint: .trailing))
                        .frame(width: geo.size.width * item.score, height: 6)
                }
            }
            .frame(height: 6)
        }
    }
}

